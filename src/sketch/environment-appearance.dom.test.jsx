import { createRequire } from 'node:module';
import { afterAll, beforeAll, expect, it, vi } from 'vitest';
import { updateSketchEnvironment } from './environment-appearance';
import { renderSketchCanvas } from './canvas-renderer';
import { defaultCADAppearance } from '../cad-appearance-store';
import { resolveAppearance } from '../viewport/appearance-themes';
const { JSDOM } = createRequire(import.meta.url)('jsdom');
let dom;
beforeAll(()=>{dom=new JSDOM();vi.stubGlobal('document',dom.window.document);});
afterAll(()=>{dom.window.close();vi.unstubAllGlobals();});
it('updates the active sketch grid and plane without altering geometry, constraints or picking identity',()=>{
  const svg=document.createElementNS('http://www.w3.org/2000/svg','svg');
  const drawing={type:'drawing',contours:[{type:'circle',center:[0,0],radius:10}],constraints:[]}, before=structuredClone(drawing);
  renderSketchCanvas(svg,drawing,{x:-80,y:-80,width:160,height:160},[]);
  const circle=svg.querySelector('[data-contour-index="0"]'), oldGrid=svg.querySelector('[data-environment-grid]'), oldCount=oldGrid.children.length;
  svg.dataset.environmentPlane='front';
  const appearance=resolveAppearance({...defaultCADAppearance,sketchGridSpacingMillimeters:5,gridMajorEvery:4,gridMinorOpacityPercent:100,gridMinorWidthPx:3,planeFrontColor:'#ff0000',planeFillOpacityPercent:25,planeLabelsVisible:false,sketchStrokeColor:'#112233'});
  updateSketchEnvironment(svg,appearance);
  expect(oldGrid.children.length).toBeGreaterThan(oldCount);
  expect(svg.querySelector('[data-environment-grid]')).toBe(oldGrid); expect(svg.querySelector('[data-contour-index="0"]')).toBe(circle);
  expect(svg.style.getPropertyValue('--cad-sketch-plane-color')).toBe('#ff0000');
  expect(svg.style.getPropertyValue('--cad-sketch-plane-fill-opacity')).toBe('0.25');
  expect(svg.style.getPropertyValue('--cad-sketch-plane-label-opacity')).toBe('0');
  expect(svg.style.getPropertyValue('--cad-sketch-grid-opacity')).toBe('1');
  expect(svg.style.getPropertyValue('--cad-sketch-grid-width')).toBe('3');
  expect(svg.style.getPropertyValue('--cad-sketch-geometry')).toBe('#112233');
  expect(oldGrid.querySelectorAll('.sketch-grid-major').length).toBeGreaterThan(0);
  const line=oldGrid.firstChild; updateSketchEnvironment(svg,appearance);expect(oldGrid.firstChild).toBe(line);
  expect(drawing).toEqual(before);expect(circle.dataset.entityConstraintState).toBe('under-constrained');
});
