"""Evaluate the authored Aether document using the existing default CAD engine.

The UI receives only generated meshes and presentation metadata. Every rollback
mesh is evaluated by FreeCAD, never reconstructed by the gallery.
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'freecad-engine'))
from aether_freecad import BuildJob, Feature, FreeCADEngine

source = Path(__file__).with_name('generated')
destination = Path(sys.argv[1]) if len(sys.argv) > 1 else source
destination.mkdir(parents=True, exist_ok=True)
native = json.loads((source / 'build.json').read_text())['features']
presentation = json.loads((source / 'presentation.json').read_text())
document = json.loads((source / 'Scifirobot.acpart').read_text())
features = [Feature(row['id'], row['kind'], row['parameters']) for row in native]
owner = {row['id']: row['bodyID'] for row in presentation['features']}
metadata = {row['id']: row for row in presentation['bodies']}
meshes = {}
proof = []

def evaluated(engine, rows):
    result = engine.build(BuildJob(features=rows, tessellation_tolerance_mm=1.5))
    if result.status != 'ok' or result.diagnostics:
        raise RuntimeError((result.message, result.diagnostics))
    return result

def pack(body):
    assert body.geometry_kind == 'solid' and body.volume_mm3 > 0
    return {'vertices': [round(x / 1000, 6) for x in body.vertices],
            'normals': [round(x, 6) for x in body.normals],
            'triangles': body.triangles}

with FreeCADEngine(timeout_seconds=120) as engine:
    result = evaluated(engine, features)
    assert {body.id for body in result.bodies} == set(metadata), [b.id for b in result.bodies]
    print(f'Full native rebuild: {len(result.bodies)} solids in {result.build_seconds:.2f}s', flush=True)
    # Each body is independently authored. Evaluate its successive native tips for
    # an exact rollback preview, including pockets, joined pads and edge finishes.
    for body_id in metadata:
        own = [row for row in features if owner.get(row.id) == body_id]
        tips = []
        for i, row in enumerate(own):
            if row.kind.startswith('sketch-'):
                continue
            rebuilt = evaluated(engine, own[:i+1])
            assert len(rebuilt.bodies) == 1 and rebuilt.bodies[0].id == body_id
            mesh_key = row.id
            meshes[mesh_key] = pack(rebuilt.bodies[0])
            tips.append({'featureID': row.id, 'mesh': mesh_key})
            proof.append({'featureID': row.id, 'bodyID': body_id,
                          'volume_mm3': rebuilt.bodies[0].volume_mm3,
                          'faces': rebuilt.bodies[0].face_count})
        final = next(body for body in result.bodies if body.id == body_id)
        assert math.isclose(final.volume_mm3, rebuilt.bodies[0].volume_mm3, rel_tol=1e-8)
        metadata[body_id]['tips'] = tips
        print(f'{body_id}: {len(tips)} evaluated tips', flush=True)
    # Prove the native circular sketch remains a geometric input, not a mesh label.
    lens = [row for row in features if owner.get(row.id) == 'lens'][:2]
    base = evaluated(engine, lens).bodies[0].volume_mm3
    edited = [Feature(lens[0].id, lens[0].kind, {**lens[0].parameters, 'radius_mm': 950}), lens[1]]
    changed = evaluated(engine, edited).bodies[0].volume_mm3
    assert math.isclose(changed - base, math.pi * (950**2 - 940**2) * 150, rel_tol=1e-8)
    print('Native sketch-radius edit changes exact solid volume as expected', flush=True)
    exported = engine.export(BuildJob(features=features), {'format': 'step'})
    if exported['status'] != 'ok':
        raise RuntimeError(exported)
    import base64
    (destination / 'Scifirobot.step').write_bytes(base64.b64decode(exported['data_base64']))

manifest = {'format': 'aether-generated-model-preview', 'version': 1,
    'source': 'Scifirobot.acpart', 'engine': result.engine,
    'features': presentation['features'], 'bodies': list(metadata.values())}
(destination / 'manifest.ts').write_text('// Generated by Aether-CAD/scripts/examples/scifirobot; do not hand-edit.\nexport const scifirobotFeatureModel = ' + json.dumps(manifest, separators=(',', ':')) + ';\n')
(destination / 'meshes.json').write_text(json.dumps(meshes, separators=(',', ':')))
(destination / 'Scifirobot.acpart').write_text(json.dumps(document, indent=2))
(source / 'proof.json').write_text(json.dumps({'engine': result.engine, 'solids': len(result.bodies),
    'features': len(document['features']), 'tips': proof}, indent=2))
print(f'Exported verified CAD document, STEP, and {len(meshes)} native rollback meshes to {destination}')
