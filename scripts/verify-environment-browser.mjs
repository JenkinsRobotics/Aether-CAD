/** Environment controls against a disposable host; never writes to live user documents. */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { partDocumentBase64, tabDocumentOf } from './browser/document-fixture.mjs';
const { chromium, expect } = createRequire(fileURLToPath(new URL('../../AetherStudio/core/files/package.json', import.meta.url)))('@playwright/test');
const origin = process.env.AETHER_TEST_ORIGIN, evidence = process.env.AETHER_FRONTEND_EVIDENCE;
assert.equal(new URL(origin).hostname, '127.0.0.1'); assert.notEqual(new URL(origin).port, '8780');
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.setDefaultTimeout(15000);
const errors = [], colors = {};
page.on('pageerror', error => errors.push(error.message));
const button = name => page.getByRole('button', { name, exact: true });
const options = async () => { await button('Display and environment').click(); };
const choose = async (role, name) => { await options(); await page.getByRole(role, { name, exact: true }).click(); };
const appearance = () => page.evaluate(() => JSON.parse(localStorage.getItem('aether-cad.appearance.studio-v2')));
try {
  await page.goto(origin + '/cad/');
  await page.locator('input[name="username"]').fill('editor');
  await page.locator('input[name="password"]').fill('account-test-password-2026');
  await button('Sign in').click();
  await expect(page.locator('input[name="password"]')).toHaveCount(0, { timeout: 30000 });
  await page.waitForLoadState('networkidle');
  const data = JSON.parse(await readFile(new URL('../service/tests/fixtures/automation-part.part.json', import.meta.url), 'utf8'));
  data.documentId = randomUUID(); data.name = 'Environment control check';
  const file = await page.evaluate(async ({ encoded, operation }) => {
    const response = await fetch('/api/library/create', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ app: 'cad', kind: 'file', scope: 'personal', operation_id: operation, name: 'Environment check.aethercad', data_base64: encoded }) });
    if (!response.ok) throw Error(await response.text()); return response.json();
  }, { encoded: partDocumentBase64(data), operation: randomUUID() });
  await page.goto(`${origin}/cad/index.html?document=${file.id}`);
  await page.getByRole('treeitem', { name: /^Extrude/ }).first().waitFor({ timeout: 90000 });
  await expect(button('Camera view')).toHaveAttribute('aria-expanded','true');
  await expect(page.locator('.aui-viewport-cube--3d canvas')).toBeVisible();
  const cube = await page.locator('#view-cube').elementHandle();
  await button('Environment').click();
  await expect(button('Snapping')).toHaveAttribute('aria-pressed','true');
  const actions = await page.locator('.aui-environment-action').evaluateAll(nodes => nodes.map(node => {
    const box=node.getBoundingClientRect(); return {x:box.x,y:box.y,width:box.width};
  }));
  assert.equal(actions.length,4);
  assert.ok(actions.every((at,i) => at.width===34 && Math.abs(at.x-actions[0].x)<1 && (!i || at.y>actions[i-1].y)));
  await button('Snapping').click();
  await expect(button('Snapping')).toHaveAttribute('aria-pressed','false');
  await button('Snapping options').click();
  await expect(page.getByRole('menuitemcheckbox',{name:'Snap to geometry',exact:true})).toBeDisabled();
  await page.keyboard.press('Escape');
  await expect(button('Camera view')).toHaveAttribute('aria-expanded','true');
  await expect(button('Environment')).toHaveAttribute('aria-expanded','true');
  await button('Snapping').click();
  await button('Snapping options').click();
  await page.getByRole('menuitemcheckbox',{name:'Snap to grid',exact:true}).click();
  assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('aether-cad.snapping'))),{enabled:true,geometry:true,grid:false});
  await button('Show grid').click();
  const floorBefore = (await appearance()).floorMode;
  await choose('menuitemcheckbox', 'Show floor');
  const floorAfter = (await appearance()).floorMode;
  assert.equal(['grid','both'].includes(floorAfter), ['grid','both'].includes(floorBefore));
  assert.notEqual(['floor','both'].includes(floorAfter), ['floor','both'].includes(floorBefore));
  await choose('menuitemradio', 'Wireframe'); assert.equal((await appearance()).displayStyle, 'wireframe');
  await choose('menuitemradio', 'Shaded'); assert.equal((await appearance()).displayStyle, 'shaded');
  await button('Camera view').click();
  await expect(page.getByRole('img', { name: 'Camera ViewCube' })).toHaveCount(0);
  await expect(button('Snapping')).toBeVisible();
  assert.equal(await cube.evaluate(node => node.isConnected), true);
  await page.reload();
  await page.getByRole('treeitem', { name: /^Extrude/ }).first().waitFor({ timeout: 90000 });
  await expect(button('Camera view')).toHaveAttribute('aria-expanded','false');
  await button('Environment').click();
  await button('Snapping options').click();
  await expect(page.getByRole('menuitemcheckbox',{name:'Snap to grid',exact:true})).toHaveAttribute('aria-checked','false');
  await page.keyboard.press('Escape');
  await button('Camera view').click();
  await button('Front view').press('Enter');
  await button('Home view').click();
  await button('Camera settings').click();
  await expect(page.getByRole('menuitemcheckbox',{name:'Show grid',exact:true})).toHaveCount(0);
  await page.getByRole('menuitemradio', { name: 'Orthographic', exact: true }).click();
  await button('Camera settings').click();
  await expect(page.getByRole('menuitemradio', { name: 'Orthographic', exact: true })).toHaveAttribute('aria-checked', 'true');
  await page.keyboard.press('Escape');
  await expect(button('Environment')).toHaveAttribute('aria-expanded','true');
  await choose('menuitem', 'Environment settings…');
  await expect(page.getByRole('combobox', { name: 'Environment preset', exact: true })).toBeVisible();
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => {
      document.documentElement.classList.toggle('aether-light-theme', theme === 'light');
      document.documentElement.dataset.aetherTheme = theme;
    }, theme);
    const surface = page.locator('.aui-environment-surface');
    await expect(surface).toHaveCSS('height', '198px');
    const targetColor = await surface.evaluate(el => {
      const probe = document.createElement('span'); probe.style.color = 'var(--aether-color-bg-panel)'; el.append(probe);
      const color = getComputedStyle(probe).color; probe.remove(); return color;
    });
    await expect(surface).toHaveCSS('background-color', targetColor);
    colors[theme] = await surface.evaluate(el => ({ background: getComputedStyle(el).backgroundColor, text: getComputedStyle(el.querySelector('button')).color }));
    assert.match(colors[theme].background, /^rgb\(/, 'surface must be opaque');
    await expect(page.locator('.aui-viewport-cube-axis-hidden').first()).toBeHidden();
    await page.screenshot({ path: join(evidence, `${theme}-environment.png`) });
    await options();
    await page.screenshot({ path: join(evidence, `${theme}-environment-menu.png`) });
    await page.keyboard.press('Escape');
    await expect(button('Environment')).toHaveAttribute('aria-expanded', 'true');
  }
  assert.notEqual(colors.light.background, colors.dark.background);
  await page.keyboard.press('Escape');
  await expect(button('Environment')).toHaveAttribute('aria-expanded', 'false');
  await expect(button('Environment')).toBeFocused();
  await expect(button('Camera view')).toHaveAttribute('aria-expanded','true');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const durations = await page.locator('.aui-environment-surface').evaluate(el => getComputedStyle(el).transitionDuration.split(',').map(parseFloat));
  assert.ok(durations.every(seconds => seconds < 0.001), 'reduced motion must remove perceptible transitions');
  await page.goto(origin + '/ui/#tab=widgets&section=showcase-environment-controls&mode=dark');
  const demo = page.locator('[data-environment-demo]');
  await expect(demo).toBeVisible({timeout:30000});
  await demo.getByRole('button',{name:'Environment',exact:true}).click();
  await expect(demo.getByRole('button',{name:'Snapping',exact:true})).toBeVisible();
  const galleryCube = demo.locator('.aui-studio-camera-content');
  await expect(galleryCube).toHaveAttribute('aria-hidden','false');
  await demo.getByRole('button',{name:'Environment',exact:true}).click();
  await expect(galleryCube).toHaveAttribute('aria-hidden','false');
  await demo.getByRole('button',{name:'Environment',exact:true}).click();
  await page.screenshot({path:join(evidence,'gallery-independent-controls.png')});
  assert.deepEqual(errors, []);
  await writeFile(join(evidence, 'result.json'), JSON.stringify({ passed: true, colors, errors }, null, 2));
  console.log('Environment controls, preferences, camera navigation, both themes and reduced motion passed.');
} catch(error) { await page.screenshot({path:join(evidence,'failure.png')}).catch(()=>{}); await writeFile(join(evidence,'failure.txt'),String(error.stack)); throw error; } finally { await browser.close(); }
