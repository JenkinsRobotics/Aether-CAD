// Extracts each canonical Part feature type's TypeScript declaration (plus the
// exported helper types it references) from the document core, so agents read
// the exact format the editor writes. Output: src/operations/feature-schemas.generated.ts
//   node scripts/generate-feature-schemas.mjs          # write
//   node scripts/generate-feature-schemas.mjs --check  # exit 1 when stale
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = ["aether-engine/src/document", "aether-engine/src/sketch", "aether-engine/src/sketch/reference"];
export const OUTPUT = join(root, "src/operations/feature-schemas.generated.ts");

/** Every exported interface/type declaration in the core, by name. */
export function declarations(files) {
  const found = new Map();
  for (const text of files) {
    const pattern = /^export (interface|type) ([A-Za-z0-9_]+)/gm;
    for (let match; (match = pattern.exec(text)); ) {
      let index = match.index, depth = 0, end = -1;
      for (let i = index; i < text.length; i++) {
        const c = text[i];
        if (c === "{" || c === "(" || c === "[") depth++;
        else if (c === "}" || c === ")" || c === "]") {
          depth--;
          if (depth === 0 && match[1] === "interface" && c === "}") { end = i + 1; break; }
        } else if (c === ";" && depth === 0 && match[1] === "type") { end = i + 1; break; }
      }
      if (end > 0) found.set(match[2], text.slice(index, end));
    }
  }
  return found;
}

function unionMembers(name, decls, seen = new Set()) {
  if (seen.has(name)) return [];
  seen.add(name);
  const text = decls.get(name) ?? "";
  const union = /^export type \w+\s*=\s*([\w\s|]+);$/s.exec(text);
  if (!union) return [name];
  return union[1].split("|").map(part => part.trim()).filter(Boolean).flatMap(part => unionMembers(part, decls, seen));
}

/** feature type literal(s) → declaration text with referenced helper types. */
export function featureSchemas(decls) {
  const schemas = {};
  for (const member of unionMembers("PartFeature", decls)) {
    const text = decls.get(member);
    if (!text) continue;
    const literal = /\btype\??:\s*((?:["'][a-z0-9-]+["']\s*\|?\s*)+)/.exec(text);
    if (!literal) continue;
    const related = [], queue = [text];
    for (let level = 0; level < 2; level++) {
      const next = [];
      for (const body of queue) for (const [name, decl] of decls) {
        const inherited = new RegExp(`extends[^{};]*\\b${name}\\b`).test(body);
        if (name === member || related.includes(decl) || (!inherited && decl.length > 4000) || !new RegExp(`\\b${name}\\b`).test(body)) continue;
        if (!inherited && unionMembers("PartFeature", decls).includes(name)) continue;
        related.push(decl); next.push(decl);
      }
      queue.splice(0, queue.length, ...next);
    }
    // Never truncate a declaration in the middle of its fields. Inherited
    // feature definitions (such as Surface Extrude) are part of the contract.
    const body = [text, ...related].join("\n\n");
    // `{...} & ({ type: "a" } | { type: "b" })` declares one shape for several types.
    // Doc comments inside the union may hold parentheses; drop them before finding the group.
    const tail = /&\s*\(([^)]*)\);?$/.exec(text.replace(/\/\*\*[\s\S]*?\*\//g, ""))?.[1];
    const variants = tail && /(^|[{;,\s])type\s*:/.test(tail) ? tail : literal[1];
    for (const type of variants.match(/["']([a-z0-9-]+)["']/g).map(value => value.slice(1, -1))) schemas[type] = body;
  }
  return Object.fromEntries(Object.entries(schemas).sort(([a], [b]) => a.localeCompare(b)));
}

export function render() {
  const files = sources.flatMap(dir => readdirSync(join(root, dir))
    .filter(name => name.endsWith(".ts") && !name.includes(".test."))
    .map(name => readFileSync(join(root, dir, name), "utf8")));
  const schemas = featureSchemas(declarations(files));
  return `// Generated by scripts/generate-feature-schemas.mjs from the document core.
// Do not edit; rerun the script after changing a feature type.
export const featureSchemas: Readonly<Record<string, string>> = ${JSON.stringify(schemas, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(), check = process.argv.includes("--check");
  let current = "";
  try { current = readFileSync(OUTPUT, "utf8"); } catch { /* first run */ }
  if (check) { if (current !== text) { console.error("feature schemas are stale: run node scripts/generate-feature-schemas.mjs"); process.exit(1); } }
  else writeFileSync(OUTPUT, text);
}
